CREATE TABLE parking_visits
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    vehicle_id     BIGINT      NOT NULL,
    spot_id        BIGINT      NOT NULL,
    reservation_id BIGINT,
    entry_type     VARCHAR(16) NOT NULL,
    entered_at     TIMESTAMPTZ NOT NULL,
    exited_at      TIMESTAMPTZ,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_parking_visits PRIMARY KEY (id),
    CONSTRAINT fk_parking_visits_vehicle FOREIGN KEY (vehicle_id)
        REFERENCES vehicles (id) ON DELETE RESTRICT,
    CONSTRAINT fk_parking_visits_spot FOREIGN KEY (spot_id)
        REFERENCES parking_spots (id) ON DELETE RESTRICT,
    CONSTRAINT fk_parking_visits_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE RESTRICT,
    CONSTRAINT uk_parking_visits_reservation UNIQUE (reservation_id),
    CONSTRAINT chk_parking_visits_entry_type CHECK (entry_type IN ('RESERVATION', 'WALK_IN')),
    CONSTRAINT chk_parking_visits_reservation_link CHECK (
        (entry_type = 'RESERVATION' AND reservation_id IS NOT NULL)
        OR (entry_type = 'WALK_IN' AND reservation_id IS NULL)
    ),
    CONSTRAINT chk_parking_visits_exit_time CHECK (exited_at IS NULL OR exited_at >= entered_at)
);

CREATE UNIQUE INDEX uk_parking_visits_active_vehicle
    ON parking_visits (vehicle_id)
    WHERE exited_at IS NULL;

CREATE UNIQUE INDEX uk_parking_visits_active_spot
    ON parking_visits (spot_id)
    WHERE exited_at IS NULL;

CREATE INDEX ix_parking_visits_vehicle_entered
    ON parking_visits (vehicle_id, entered_at DESC, id DESC);
