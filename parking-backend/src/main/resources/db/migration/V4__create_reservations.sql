CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER TABLE vehicles
    ADD CONSTRAINT uk_vehicles_id_user UNIQUE (id, user_id);

CREATE TABLE reservations
(
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id         BIGINT      NOT NULL,
    vehicle_id      BIGINT      NOT NULL,
    spot_id         BIGINT      NOT NULL,
    start_at        TIMESTAMPTZ NOT NULL,
    end_at          TIMESTAMPTZ NOT NULL,
    status          VARCHAR(32) NOT NULL,
    hold_expires_at TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    confirmed_at    TIMESTAMPTZ,
    cancelled_at    TIMESTAMPTZ,

    CONSTRAINT pk_reservations PRIMARY KEY (id),
    CONSTRAINT fk_reservations_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_vehicle_owner FOREIGN KEY (vehicle_id, user_id)
        REFERENCES vehicles (id, user_id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservations_spot FOREIGN KEY (spot_id) REFERENCES parking_spots (id) ON DELETE RESTRICT,
    CONSTRAINT chk_reservations_interval CHECK (end_at > start_at),
    CONSTRAINT chk_reservations_status CHECK (status IN (
        'HELD',
        'HOLD_EXPIRED',
        'HOLD_RELEASED',
        'ACTIVE',
        'CANCELLED',
        'EXPIRED',
        'CHECKED_IN',
        'COMPLETED'
    )),
    CONSTRAINT chk_reservations_hold_expiry CHECK (status <> 'HELD' OR hold_expires_at IS NOT NULL),
    CONSTRAINT chk_reservations_hold_before_start CHECK (
        hold_expires_at IS NULL OR hold_expires_at <= start_at
    ),
    CONSTRAINT chk_reservations_confirmation CHECK (status <> 'ACTIVE' OR confirmed_at IS NOT NULL),
    CONSTRAINT chk_reservations_cancellation CHECK (
        status NOT IN ('HOLD_RELEASED', 'CANCELLED') OR cancelled_at IS NOT NULL
    )
);

ALTER TABLE reservations
    ADD CONSTRAINT ex_reservations_spot_interval
        EXCLUDE USING gist
        (
            spot_id WITH =,
            tstzrange(start_at, end_at, '[)') WITH &&
        )
        WHERE (status IN ('HELD', 'ACTIVE', 'CHECKED_IN'));

ALTER TABLE reservations
    ADD CONSTRAINT ex_reservations_vehicle_interval
        EXCLUDE USING gist
        (
            vehicle_id WITH =,
            tstzrange(start_at, end_at, '[)') WITH &&
        )
        WHERE (status IN ('HELD', 'ACTIVE', 'CHECKED_IN'));

CREATE INDEX ix_reservations_user_status_start
    ON reservations (user_id, status, start_at, id);

CREATE INDEX ix_reservations_expiring_holds
    ON reservations (hold_expires_at, id)
    WHERE status = 'HELD';
