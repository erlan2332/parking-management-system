CREATE TABLE invoices
(
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    visit_id               BIGINT         NOT NULL,
    status                 VARCHAR(16)    NOT NULL,
    issued_at              TIMESTAMPTZ    NOT NULL,
    entered_at             TIMESTAMPTZ    NOT NULL,
    exited_at              TIMESTAMPTZ    NOT NULL,
    vehicle_plate          VARCHAR(32)    NOT NULL,
    spot_code              VARCHAR(10)    NOT NULL,
    pricing_zone_id        VARCHAR(64)    NOT NULL,
    currency               VARCHAR(3)     NOT NULL,
    total_duration_seconds BIGINT         NOT NULL,
    day_duration_seconds   BIGINT         NOT NULL,
    night_duration_seconds BIGINT         NOT NULL,
    day_rate_per_minute    NUMERIC(19, 6) NOT NULL,
    night_rate_per_minute  NUMERIC(19, 6) NOT NULL,
    day_cost               NUMERIC(19, 6) NOT NULL,
    night_cost             NUMERIC(19, 6) NOT NULL,
    total_amount           NUMERIC(19, 2) NOT NULL,

    CONSTRAINT pk_invoices PRIMARY KEY (id),
    CONSTRAINT fk_invoices_visit FOREIGN KEY (visit_id)
        REFERENCES parking_visits (id) ON DELETE RESTRICT,
    CONSTRAINT uk_invoices_visit UNIQUE (visit_id),
    CONSTRAINT chk_invoices_status CHECK (status = 'ISSUED'),
    CONSTRAINT chk_invoices_currency CHECK (currency = 'KGS'),
    CONSTRAINT chk_invoices_interval CHECK (exited_at >= entered_at),
    CONSTRAINT chk_invoices_issued_after_exit CHECK (issued_at >= exited_at),
    CONSTRAINT chk_invoices_duration_non_negative CHECK (
        total_duration_seconds >= 0
        AND day_duration_seconds >= 0
        AND night_duration_seconds >= 0
    ),
    CONSTRAINT chk_invoices_duration_sum CHECK (
        day_duration_seconds + night_duration_seconds = total_duration_seconds
    ),
    CONSTRAINT chk_invoices_rates_non_negative CHECK (
        day_rate_per_minute >= 0 AND night_rate_per_minute >= 0
    ),
    CONSTRAINT chk_invoices_costs_non_negative CHECK (
        day_cost >= 0 AND night_cost >= 0 AND total_amount >= 0
    ),
    CONSTRAINT chk_invoices_vehicle_plate_not_blank CHECK (BTRIM(vehicle_plate) <> ''),
    CONSTRAINT chk_invoices_spot_code_not_blank CHECK (BTRIM(spot_code) <> ''),
    CONSTRAINT chk_invoices_pricing_zone_not_blank CHECK (BTRIM(pricing_zone_id) <> '')
);

CREATE INDEX ix_invoices_issued_at
    ON invoices (issued_at DESC, id DESC);
