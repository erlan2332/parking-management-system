CREATE TABLE users
(
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email         VARCHAR(320) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_users PRIMARY KEY (id),
    CONSTRAINT chk_users_email_not_blank CHECK (BTRIM(email) <> ''),
    CONSTRAINT chk_users_email_trimmed CHECK (email = BTRIM(email)),
    CONSTRAINT chk_users_password_hash_not_blank CHECK (BTRIM(password_hash) <> '')
);

CREATE UNIQUE INDEX uk_users_email_lower ON users (LOWER(email));

CREATE TABLE vehicles
(
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY,
    user_id          BIGINT      NOT NULL,
    plate_number     VARCHAR(32) NOT NULL,
    normalized_plate VARCHAR(32) NOT NULL,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT pk_vehicles PRIMARY KEY (id),
    CONSTRAINT fk_vehicles_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT uk_vehicles_normalized_plate UNIQUE (normalized_plate),
    CONSTRAINT chk_vehicles_plate_number_not_blank CHECK (BTRIM(plate_number) <> ''),
    CONSTRAINT chk_vehicles_normalized_plate_not_blank CHECK (BTRIM(normalized_plate) <> '')
);

CREATE INDEX idx_vehicles_user_id ON vehicles (user_id);
