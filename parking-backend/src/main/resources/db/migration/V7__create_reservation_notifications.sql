CREATE TABLE reservation_notifications
(
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reservation_id        BIGINT      NOT NULL,
    notification_type     VARCHAR(64) NOT NULL,
    status                VARCHAR(16) NOT NULL,
    created_at            TIMESTAMPTZ NOT NULL,
    processing_started_at TIMESTAMPTZ,
    sent_at               TIMESTAMPTZ,
    attempt_count         INTEGER     NOT NULL DEFAULT 0,
    last_error            VARCHAR(512),

    CONSTRAINT pk_reservation_notifications PRIMARY KEY (id),
    CONSTRAINT fk_reservation_notifications_reservation FOREIGN KEY (reservation_id)
        REFERENCES reservations (id) ON DELETE RESTRICT,
    CONSTRAINT uk_reservation_notifications_reservation_type
        UNIQUE (reservation_id, notification_type),
    CONSTRAINT chk_reservation_notifications_type CHECK (
        notification_type = 'RESERVATION_ENDING_SOON'
    ),
    CONSTRAINT chk_reservation_notifications_status CHECK (
        status IN ('PENDING', 'SENDING', 'SENT', 'FAILED')
    ),
    CONSTRAINT chk_reservation_notifications_attempt_count CHECK (attempt_count >= 0),
    CONSTRAINT chk_reservation_notifications_sending_time CHECK (
        status <> 'SENDING' OR processing_started_at IS NOT NULL
    ),
    CONSTRAINT chk_reservation_notifications_sent_time CHECK (
        status <> 'SENT' OR sent_at IS NOT NULL
    )
);

CREATE INDEX ix_reservation_notifications_processing
    ON reservation_notifications (status, processing_started_at, id)
    WHERE status IN ('PENDING', 'SENDING', 'FAILED');

CREATE INDEX ix_reservations_active_entry_deadline
    ON reservations (start_at, end_at, id)
    WHERE status = 'ACTIVE';
